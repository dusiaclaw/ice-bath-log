#!/usr/bin/env python3
"""Builds lang.js from tools/lang-src.txt (English ||| Deutsch ||| Français ||| Italiano)."""
import json,sys,os
here=os.path.dirname(os.path.abspath(__file__));root=os.path.dirname(here)
langs=['de','fr','it'];out={l:{} for l in langs};bad=0
for n,line in enumerate(open(os.path.join(here,'lang-src.txt'),encoding='utf-8'),1):
    line=line.rstrip('\n')
    if not line.strip() or line.startswith('#'):continue
    p=[x.strip() for x in line.split('|||')]
    if len(p)!=4 or not all(p):print('line',n,'needs 4 parts:',line[:60]);bad+=1;continue
    for l,t in zip(langs,p[1:]):out[l][p[0]]=t
if bad:sys.exit(1)
open(os.path.join(root,'lang.js'),'w',encoding='utf-8').write('/* generated by tools/make-lang.py from tools/lang-src.txt – do not edit */\nwindow.I18N='+json.dumps(out,ensure_ascii=False,indent=0)+';\n')
print({l:len(v) for l,v in out.items()})
